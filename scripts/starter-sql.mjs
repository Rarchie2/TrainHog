// Writes supabase/migrations/0002_starter_library.sql from the starter
// exercises and sessions in src/data/sample.ts, so a new business starts
// with the same library as the demo. Run: node --experimental-strip-types scripts/starter-sql.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const { exercises, sessions } = await import('../src/data/sample.ts');
// Stable uuids from the sample ids, so running it twice changes nothing.
const uuid = (s) => {
  const h = createHash('sha1').update('trainhog:' + s).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
export const BUSINESS = '7a1e5b0d-0000-4000-a000-000000000001';

let sql = `-- Starter library for Hogan's business: ${exercises.length} exercises and ${sessions.length} sessions.
-- Generated by scripts/starter-sql.mjs from src/data/sample.ts. Safe to run more than once.

insert into public.businesses (id, name, trainer_name, town, brand_color)
values ('${BUSINESS}', 'TrainHog', 'Hogan', 'Winchester', '#1E5BD8')
on conflict (id) do nothing;

`;
for (const e of exercises) {
  sql += `insert into public.exercises (id, business_id, name, video_length, coaching_notes, steps, easier, harder, tags) values (${q(uuid(e.id))}, '${BUSINESS}', ${q(e.name)}, ${q(e.videoLength)}, ${q(e.coachingNotes)}, ${arr(e.steps)}, ${q(e.easier)}, ${q(e.harder)}, ${arr(e.tags)}) on conflict (id) do nothing;\n`;
}
sql += '\n';
for (const s of sessions) {
  const items = s.exercises.map((x) => ({ ...x, exerciseId: uuid(x.exerciseId) }));
  sql += `insert into public.sessions (id, business_id, name, category, minutes, equipment, level, purpose, safety_note, exercises) values (${q(uuid(s.id))}, '${BUSINESS}', ${q(s.name)}, ${q(s.category)}, ${s.minutes}, ${q(s.equipment)}, ${s.level}, ${q(s.purpose)}, ${q(s.safetyNote)}, ${q(JSON.stringify(items))}::jsonb) on conflict (id) do nothing;\n`;
}
writeFileSync(new URL('../supabase/migrations/0002_starter_library.sql', import.meta.url), sql);
console.log('wrote', exercises.length, 'exercises and', sessions.length, 'sessions');
